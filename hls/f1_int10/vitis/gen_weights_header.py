"""
Generate a synthesizable C++ header of all int10 model constants as flat
`static const` arrays, from the exported hls/f1_int10/data/ text files.

Vitis HLS cannot synthesize the portable core's std::map/std::string/file IO
param loading. This header replaces `load_params()` for synthesis: every tensor
becomes a compile-time constant array the top function indexes directly. C-sim
still uses the text loader (params_io.cpp); synthesis uses this header.

Run
---
    python hls/f1_int10/vitis/gen_weights_header.py
    # writes hls/f1_int10/vitis/weights_int10.h and prints a verification summary
"""
from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data"
OUT = HERE / "weights_int10.h"

# layer prefixes present for the 1-layer model
LIN_NAMES = ["proj", "cls1", "cls4",
             "l0.wq", "l0.wk", "l0.wv", "l0.out", "l0.ff0", "l0.ff3"]
LN_NAMES = ["l0.ln1", "l0.ln2", "cls_ln"]


def _read(name):
    toks = (DATA / name).read_text().split()
    return int(toks[0]), toks[1:]


def _cident(name):
    return name.replace(".", "_")


def emit_int_array(fh, cname, values):
    fh.write(f"static const long {cname}[{len(values)}] = {{")
    fh.write(",".join(values))
    fh.write("};\n")


def emit_double_array(fh, cname, values):
    fh.write(f"static const double {cname}[{len(values)}] = {{")
    fh.write(",".join(values))
    fh.write("};\n")


def main():
    total = 0
    with open(OUT, "w", encoding="ascii") as fh:
        fh.write("// AUTO-GENERATED by gen_weights_header.py -- do not edit.\n")
        fh.write("// Flat int10 model constants for Vitis HLS synthesis of the\n")
        fh.write("// F_1layer core. Regenerate from hls/f1_int10/data/ after any re-export.\n")
        fh.write("#ifndef WEIGHTS_INT10_H\n#define WEIGHTS_INT10_H\n\n")

        # linear weights + folded biases + requant multipliers
        for n in LIN_NAMES:
            c = _cident(n)
            _, w = _read(f"W_{n}.txt");  emit_int_array(fh, f"W_{c}", w);  total += len(w)
            _, b = _read(f"b_{n}.txt");  emit_int_array(fh, f"b_{c}", b);  total += len(b)
            _, m = _read(f"M_{n}.txt");  emit_double_array(fh, f"M_{c}", m)

        # attention requant multipliers + mean pool
        for n in ["l0.scores", "l0.ctx"]:
            _, m = _read(f"M_{n}.txt");  emit_double_array(fh, f"M_{_cident(n)}", m)
        _, m = _read("M_pool.txt");      emit_double_array(fh, "M_pool", m)

        # residual add ratios (2 each)
        for n in ["l0.res1", "l0.res2"]:
            _, a = _read(f"add_{n}.txt"); emit_double_array(fh, f"add_{_cident(n)}", a)

        # positional encoding
        _, pe = _read("pe_codes.txt");   emit_int_array(fh, "pe_codes", pe); total += len(pe)

        # layernorm folded affine + integer eps
        for n in LN_NAMES:
            c = _cident(n)
            _, gm = _read(f"ln_gm_{n}.txt"); emit_double_array(fh, f"ln_gm_{c}", gm)
            _, bt = _read(f"ln_bt_{n}.txt"); emit_double_array(fh, f"ln_bt_{c}", bt)
            _, ep = _read(f"ln_epsq_{n}.txt"); fh.write(f"static const long ln_epsq_{c} = {ep[0]};\n")

        # LUTs
        _, g = _read("gelu_l0.txt");     emit_int_array(fh, "gelu_l0", g);   total += len(g)
        _, g = _read("gelu_cls.txt");    emit_int_array(fh, "gelu_cls", g);  total += len(g)
        _, e = _read("exp_l0.txt");      emit_int_array(fh, "exp_l0", e);    total += len(e)
        _, ec = _read("exp_clamp_l0.txt"); fh.write(f"static const int exp_clamp_l0 = {ec[0]};\n")
        _, r = _read("rsqrt.txt");       emit_int_array(fh, "rsqrt_lut", r); total += len(r)

        fh.write("\n#endif // WEIGHTS_INT10_H\n")

    print(f"[gen] wrote {OUT}")
    print(f"[gen] total array elements: {total}")
    print(f"[gen] header size: {OUT.stat().st_size/1024:.1f} KB")


if __name__ == "__main__":
    main()
