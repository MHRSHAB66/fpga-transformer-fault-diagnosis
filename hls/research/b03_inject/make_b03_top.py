"""Generate the B03 research top: the B02 integrity top plus programmable logical
fault injection (research ABI, AXI-Lite inputs inj_site / inj_word / inj_bit).

  inj_site 0  no injection (must reproduce the canonical logits/class, status 0)
  inj_site 1  flip bit inj_bit (0..9) of input-buffer word inj_word after the ingress
              wrote it (and after the first signature): stored-code upset
  inj_site 2  flip bit inj_bit (0..31) of projection accumulator inj_word
              (row * 32 + output) before its range check and requant
  inj_site 3  flip bit inj_bit (0..9) of output logit inj_word & 3 of the first
              classifier-tail copy (before the duplicate comparison and the outputs)
Flips use the hardware widths (10-bit two's complement codes, 32-bit accumulators)
in both the ap_int (HLS) and the native C-model builds. This is logical fault
emulation in the datapath, not radiation or configuration-memory testing.
Inputs are sampled per invocation: the board runner starts the core per window
(ap_start) after writing the registers. Generated from the B02 top (which is
generated from the canonical top); no canonical file is modified.
"""
from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
B02 = HERE.parent / "b02_integrity"
SRC = B02 / "transformer_top_seq256_raw1024_b02_argmax.cpp"
DST = HERE / "transformer_top_seq256_raw1024_b03_argmax.cpp"


def sub(src, old, new):
    assert src.count(old) == 1, old[:90]
    return src.replace(old, new)


def make_top():
    s = SRC.read_text()
    banner = ("// B03 RESEARCH VARIANT (2026-11-13), generated by hls/research/b03_inject/make_b03_top.py\n"
              "// from the B02 top: adds programmable logical fault injection (inj_site/inj_word/inj_bit).\n")
    helpers = (
        "\n// B03: single-bit flips at the hardware widths (identical in ap_int and native builds).\n"
        "static inline act_t flip10(act_t v, int bit) {\n"
        "    int u = ((int)v) & 0x3FF;\n"
        "    u ^= (1 << (bit & 15)) & 0x3FF;\n"
        "    return (act_t)(u >= 512 ? u - 1024 : u);\n"
        "}\n"
        "static inline long flip32(long v, int bit) {\n"
        "    unsigned int u = (unsigned int)(int)v;\n"
        "    u ^= 1u << (bit & 31);\n"
        "    return (long)(int)u;\n"
        "}\n")
    anchor = "\n// B02: canonical linear_fixed plus a proven-range comparison"
    s = sub(s, anchor, helpers + anchor)
    s = sub(s, "                                  scale_t Mq, act_t* out, int& range_err) {",
            "                                  scale_t Mq, act_t* out, int& range_err,\n"
            "                                  int inj_idx, int inj_bit) {")
    s = sub(s, "            const long a = (long)acc + b[o];",
            "            if (r * DOUT + o == inj_idx) acc = flip32((long)acc, inj_bit);   // B03 site 2\n"
            "            const long a = (long)acc + b[o];")
    s = sub(s, "                             int& input_sig_after, int& range_err, int& tail_err) {",
            "                             int& input_sig_after, int& range_err, int& tail_err,\n"
            "                             int inj_site, int inj_word, int inj_bit) {")
    s = sub(s, "    linear_fixed_rangechk<SEQ, CH, D>(input, W_proj, b_proj, M_proj_q40[0], x_in, range_err);",
            "    linear_fixed_rangechk<SEQ, CH, D>(input, W_proj, b_proj, M_proj_q40[0], x_in, range_err,\n"
            "                                      inj_site == 2 ? inj_word : -1, inj_bit);")
    s = sub(s, "    // B02 bit1: duplicated classifier tail (second evaluation of cls4 + argmax)\n",
            "    if (inj_site == 3) logits[inj_word & 3] = flip10(logits[inj_word & 3], inj_bit);   // B03 site 3\n"
            "    // B02 bit1: duplicated classifier tail (second evaluation of cls4 + argmax)\n")
    s = sub(s, "                     int& pred_class, int& integrity_status) {",
            "                     int& pred_class, int& integrity_status,\n"
            "                     int inj_site, int inj_word, int inj_bit) {")
    s = sub(s, "#pragma HLS INTERFACE s_axilite port=integrity_status bundle=ctrl\n",
            "#pragma HLS INTERFACE s_axilite port=integrity_status bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=inj_site bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=inj_word bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=inj_bit bundle=ctrl\n")
    s = sub(s, "    act_t logits[NUM_CLASSES];\n    int sig_after = 0, range_err = 0, tail_err = 0;\n",
            "    if (inj_site == 1) {   // B03 site 1: stored input-code upset after the first signature\n"
            "        const int w = inj_word & (SEQ * CH - 1);\n"
            "        input[w] = flip10(input[w], inj_bit);\n"
            "    }\n"
            "    act_t logits[NUM_CLASSES];\n    int sig_after = 0, range_err = 0, tail_err = 0;\n")
    s = sub(s, "    transformer_core(input, logits, sig_after, range_err, tail_err);",
            "    transformer_core(input, logits, sig_after, range_err, tail_err, inj_site, inj_word, inj_bit);")
    DST.write_text(banner + s)
    print("wrote", DST)


def make_harnesses():
    b = (B02 / "batch_logits_b02.cpp").read_text()
    b = sub(b, "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class, int& integrity_status);",
            "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class, int& integrity_status,\n"
            "                     int inj_site, int inj_word, int inj_bit);\n"
            "#include <fstream>\nstatic std::ifstream g_inj;   // argv[3]: one 'site word bit' line per window (optional)")
    b = sub(b, "        int pred_class = -1, integrity_status = -1;\n        transformer_top(in, out, pred_class, integrity_status);",
            "        int pred_class = -1, integrity_status = -1, site = 0, word = 0, bit = 0;\n"
            "        if (g_inj.is_open() && !(g_inj >> site >> word >> bit)) { site = 0; word = 0; bit = 0; }\n"
            "        transformer_top(in, out, pred_class, integrity_status, site, word, bit);")
    b = sub(b, "    if (argc != 3) {", "    if (argc == 4) g_inj.open(argv[3]);\n    if (argc != 3 && argc != 4) {")
    (HERE / "batch_logits_b03.cpp").write_text("// B03 batch C-model harness (generated from batch_logits_b02.cpp);\n"
                                               "// optional argv[3] = injection manifest, one 'site word bit' per window.\n" + b)
    t = (B02 / "testbench_b02.cpp").read_text()
    t = sub(t, "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class, int& integrity_status);",
            "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class, int& integrity_status,\n"
            "                     int inj_site, int inj_word, int inj_bit);")
    t = sub(t, "        transformer_top(in, out, pred_class, integrity_status);",
            "        transformer_top(in, out, pred_class, integrity_status, 0, 0, 0);   // injection off")
    (HERE / "testbench_b03.cpp").write_text("// B03 HLS testbench (generated from testbench_b02.cpp): injection off,\n"
                                            "// canonical goldens exact and integrity_status 0.\n" + t)
    print("wrote harnesses")


if __name__ == "__main__":
    make_top()
    make_harnesses()
