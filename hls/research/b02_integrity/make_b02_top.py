"""Generate the B02 research top (selective integrity checks) from the canonical
raw-input argmax top, which is only read. Also generates its C-model batch
harness and HLS testbench from the canonical ones.

Checks (research ABI: extra AXI-Lite output register `integrity_status`):
  bit0 input-buffer signature: XOR fold of every input-buffer word, computed when
       the ingress has written the buffer and again after the projection has read
       it; any single flipped bit of a stored input code changes the fold
  bit1 duplicated classifier tail: cls4 + argmax computed a second time and compared
  bit2 projection accumulator outside its proven legal bound (511*sum|W|+|b|,
       computed here from weights_int10.h; inputs are clamped to +-511)
The class (pred_class) and the 4 logits are produced exactly as in the canonical
top; integrity_status is metadata, never a fifth class.
"""
from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
VITIS = REPO / "hls/f1_int10_seq256/vitis"
HERE = Path(__file__).resolve().parent
SRC = VITIS / "transformer_top_seq256_raw1024_dsp_margin_argmax.cpp"
DST = HERE / "transformer_top_seq256_raw1024_b02_argmax.cpp"


def proj_bound():
    s = (VITIS / "weights_int10.h").read_text()
    def arr(name):
        m = re.search(r"%s\[[^\]]*\]\s*=\s*\{([^}]*)\}" % re.escape(name), s)
        return [int(x) for x in m.group(1).split(",") if x.strip()]
    W, b = arr("W_proj"), arr("b_proj")
    din = len(W) // len(b)
    return max(511 * sum(abs(w) for w in W[o * din:(o + 1) * din]) + abs(b[o]) for o in range(len(b)))


def sub(src, old, new):
    assert src.count(old) == 1, old[:80]
    return src.replace(old, new)


def make_top():
    bound = proj_bound()
    s = SRC.read_text()
    banner = (
        "// ---------------------------------------------------------------------------\n"
        "// B02 RESEARCH VARIANT (2026-11-13), generated by hls/research/b02_integrity/\n"
        "// make_b02_top.py from transformer_top_seq256_raw1024_dsp_margin_argmax.cpp (NOT\n"
        "// modified). Adds selective integrity checks reported on the research AXI-Lite\n"
        "// register integrity_status (bit0 input-buffer signature, bit1 duplicated\n"
        "// classifier tail, bit2 projection accumulator range). Logits and class are\n"
        "// computed exactly as in the canonical top.\n"
        "// ---------------------------------------------------------------------------\n")
    # checked projection: canonical linear_fixed plus a comparison against the proven bound
    chk = (
        "\n// B02: canonical linear_fixed plus a proven-range comparison of every\n"
        "// accumulator (|acc + b| <= PROJ_ACC_BOUND for all legal inputs).\n"
        "static const long PROJ_ACC_BOUND = %d;\n"
        "template<int ROWS, int DIN, int DOUT>\n"
        "static void linear_fixed_rangechk(const act_t* in, const long* W, const long* b,\n"
        "                                  scale_t Mq, act_t* out, int& range_err) {\n"
        "    int err = 0;\n"
        "    for (int r = 0; r < ROWS; ++r)\n"
        "        for (int o = 0; o < DOUT; ++o) {\n"
        "            const long* wo = &W[(long)o * DIN];\n"
        "            const act_t* xr = &in[(long)r * DIN];\n"
        "            acc_t acc = 0;\n"
        "            for (int i = 0; i < DIN; ++i) {\n"
        "#pragma HLS PIPELINE\n"
        "                acc += xr[i] * wo[i];\n"
        "            }\n"
        "            const long a = (long)acc + b[o];\n"
        "            if (a > PROJ_ACC_BOUND || a < -PROJ_ACC_BOUND) err = 1;\n"
        "            out[(long)r * DOUT + o] = requant(acc + b[o], Mq);\n"
        "        }\n"
        "    range_err = err;\n"
        "}\n") % bound
    anchor = "// Resource-margin variant for the classifier only."
    s = sub(s, anchor, chk + "\n" + anchor)
    s = sub(s, "static void transformer_core(const act_t* input, act_t logits[NUM_CLASSES]) {",
            "static void transformer_core(const act_t* input, act_t logits[NUM_CLASSES],\n"
            "                             int& input_sig_after, int& range_err, int& tail_err) {")
    s = sub(s, "    linear_fixed<SEQ, CH, D>(input, W_proj, b_proj, M_proj_q40[0], x_in);\n",
            "    linear_fixed_rangechk<SEQ, CH, D>(input, W_proj, b_proj, M_proj_q40[0], x_in, range_err);\n"
            "    // B02 bit0: input-buffer signature after the projection has read it\n"
            "    int sig = 0;\n"
            "    for (int i = 0; i < SEQ * CH; ++i) {\n"
            "#pragma HLS PIPELINE\n"
            "        sig ^= ((int)input[i]) & 0x3FF;   // 10-bit code pattern\n"
            "    }\n"
            "    input_sig_after = sig;\n")
    s = sub(s, "    linear_fixed_lut<CLS_HID, NUM_CLASSES>(c1, W_cls4, b_cls4, M_cls4_q40[0], logits);\n}",
            "    linear_fixed_lut<CLS_HID, NUM_CLASSES>(c1, W_cls4, b_cls4, M_cls4_q40[0], logits);\n"
            "    // B02 bit1: duplicated classifier tail (second evaluation of cls4 + argmax)\n"
            "    act_t logits_dup[NUM_CLASSES];\n"
            "    linear_fixed_lut<CLS_HID, NUM_CLASSES>(c1, W_cls4, b_cls4, M_cls4_q40[0], logits_dup);\n"
            "    int diff = 0;\n"
            "    for (int c = 0; c < NUM_CLASSES; ++c)\n"
            "        if (logits_dup[c] != logits[c]) diff = 1;\n"
            "    if (argmax_first_max<act_t, NUM_CLASSES>(logits_dup) != argmax_first_max<act_t, NUM_CLASSES>(logits)) diff = 1;\n"
            "    tail_err = diff;\n}")
    s = sub(s, "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out,\n                     int& pred_class) {",
            "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out,\n"
            "                     int& pred_class, int& integrity_status) {")
    s = sub(s, "#pragma HLS INTERFACE s_axilite port=pred_class bundle=ctrl\n",
            "#pragma HLS INTERFACE s_axilite port=pred_class bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=integrity_status bundle=ctrl\n")
    s = sub(s, "    raw_ingress<axis_t, act_t, INPUT_SEQ, SEQ, CH>(in, input);\n    act_t logits[NUM_CLASSES];\n    transformer_core(input, logits);\n",
            "    raw_ingress<axis_t, act_t, INPUT_SEQ, SEQ, CH>(in, input);\n"
            "    // B02 bit0: input-buffer signature right after the ingress wrote it\n"
            "    int sig_before = 0;\n"
            "    for (int i = 0; i < SEQ * CH; ++i) {\n"
            "#pragma HLS PIPELINE\n"
            "        sig_before ^= ((int)input[i]) & 0x3FF;\n"
            "    }\n"
            "    act_t logits[NUM_CLASSES];\n"
            "    int sig_after = 0, range_err = 0, tail_err = 0;\n"
            "    transformer_core(input, logits, sig_after, range_err, tail_err);\n"
            "    integrity_status = (sig_after != sig_before ? 1 : 0) | (tail_err << 1) | (range_err << 2);\n")
    DST.write_text(banner + s)
    print("wrote", DST, "proj bound", bound)


def make_harnesses():
    b = (REPO / "hls/f1_int10_seq256/gpp_csim/batch_logits.cpp").read_text()
    b = sub(b, "#ifdef WITH_PRED_CLASS\nvoid transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class);",
            "#ifdef WITH_PRED_CLASS\nvoid transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class, int& integrity_status);")
    b = sub(b, "        int pred_class = -1;\n        transformer_top(in, out, pred_class);",
            "        int pred_class = -1, integrity_status = -1;\n        transformer_top(in, out, pred_class, integrity_status);")
    b = sub(b, "        std::printf(\"%ld %lld %lld %lld %lld %d\\n\", first + done, lg[0], lg[1], lg[2], lg[3],\n                    pred_class);",
            "        std::printf(\"%ld %lld %lld %lld %lld %d %d\\n\", first + done, lg[0], lg[1], lg[2], lg[3],\n                    pred_class, integrity_status);")
    (HERE / "batch_logits_b02.cpp").write_text(
        "// B02 batch C-model harness, generated by make_b02_top.py from\n"
        "// hls/f1_int10_seq256/gpp_csim/batch_logits.cpp; prints integrity_status as a 7th column.\n" + b)
    t = (VITIS / "testbench_ingress1024_argmax.cpp").read_text()
    t = sub(t, "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class);",
            "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class, int& integrity_status);")
    t = sub(t, "        int pred_class = -1;\n        transformer_top(in, out, pred_class);",
            "        int pred_class = -1, integrity_status = -1;\n        transformer_top(in, out, pred_class, integrity_status);")
    t = sub(t, "        exact &= pred_class == expected_class && pred_class == ref;",
            "        exact &= pred_class == expected_class && pred_class == ref && integrity_status == 0;")
    (HERE / "testbench_b02.cpp").write_text(
        "// B02 HLS testbench, generated by make_b02_top.py from testbench_ingress1024_argmax.cpp;\n"
        "// additionally requires integrity_status == 0 on every golden vector.\n" + t)
    print("wrote harness templates (call sites patched next)")


if __name__ == "__main__":
    make_top()
    make_harnesses()
