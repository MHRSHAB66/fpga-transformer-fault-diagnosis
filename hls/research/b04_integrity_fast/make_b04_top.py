"""Generate the B04 research top from the B03 top (B02 checks + injection), which is
only read. B04 changes only the checked projection:

  * latency: B02/B03 placed the range comparison after the inner MAC loop, which
    stopped Vitis HLS from flattening the projection nest (21 cycles per output,
    172,032 cycles, +1.1 ms). B04 writes the projection as ONE pipelined loop over
    ROWS*DOUT*DIN (II=1), the schedule HLS builds for the canonical linear_fixed
    (65,546 cycles), with the comparison inside it.
  * coverage: a per-row checksum (algorithm-based fault tolerance) is added:
    sum_o acc[r][o] must equal sum_i x[r][i] * WSUM[i], WSUM[i] = sum_o W[o][i]
    (exact integers, computed here from weights_int10.h). Any change of a single
    accumulator changes the row sum, including the projection-accumulator bit 18-19
    flips that stay inside the proven range and were silent in B03.
    New bit3 of integrity_status. The second product uses fabric logic (BIND_OP).

Injection (B03 sites 1-3) is compiled only with -DB04_INJECT (research overlay
b04i); without it the injection inputs are constant 0 and the logic disappears
(overlay b04, used for the cost and latency measurements). Logits and class are
computed exactly as in the canonical top in both builds.
"""
from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
VITIS = REPO / "hls/f1_int10_seq256/vitis"
HERE = Path(__file__).resolve().parent
B03 = HERE.parent / "b03_inject"
SRC = B03 / "transformer_top_seq256_raw1024_b03_argmax.cpp"
DST = HERE / "transformer_top_seq256_raw1024_b04_argmax.cpp"


def weights():
    s = (VITIS / "weights_int10.h").read_text()
    def arr(name):
        m = re.search(r"%s\[[^\]]*\]\s*=\s*\{([^}]*)\}" % re.escape(name), s)
        return [int(x) for x in m.group(1).split(",") if x.strip()]
    return arr("W_proj"), arr("b_proj")


def sub(src, old, new):
    assert src.count(old) == 1, old[:90]
    return src.replace(old, new)


def make_top():
    W, b = weights()
    dout = len(b)
    din = len(W) // dout
    wsum = [sum(W[o * din + i] for o in range(dout)) for i in range(din)]
    bound = max(511 * sum(abs(w) for w in W[o * din:(o + 1) * din]) + abs(b[o]) for o in range(dout))
    s = SRC.read_text()
    assert "static const long PROJ_ACC_BOUND = %d;" % bound in s
    banner = ("// B04 RESEARCH VARIANT (2026-11-14), generated by hls/research/b04_integrity_fast/make_b04_top.py\n"
              "// from the B03 top: single-pipeline checked projection (removes the B02 +1.1 ms) and a\n"
              "// per-row checksum (integrity_status bit3). Injection only with -DB04_INJECT.\n")
    start = s.index("// B02: canonical linear_fixed plus a proven-range comparison")
    end = s.index("    range_err = err;\n}\n", start) + len("    range_err = err;\n}\n")
    chk = (
        "// B04: the B02 projection checks in ONE pipelined loop over ROWS*DOUT*DIN (the\n"
        "// schedule Vitis HLS builds for the canonical linear_fixed), plus a per-row\n"
        "// checksum: sum_o acc[r][o] == sum_i x[r][i] * PROJ_WSUM[i] (exact integers).\n"
        "static const long PROJ_ACC_BOUND = %d;\n"
        "static const long PROJ_WSUM[%d] = {%s};   // sum over outputs of W_proj[o][i]\n"
        "template<int ROWS, int DIN, int DOUT>\n"
        "static void linear_fixed_chk(const act_t* in, const long* W, const long* b,\n"
        "                             scale_t Mq, act_t* out, int& range_err, int& sum_err,\n"
        "                             int inj_idx, int inj_bit) {\n"
        "    int rerr = 0, serr = 0;\n"
        "    acc_t acc = 0, rowsum = 0, chk = 0;\n"
        "    for (unsigned t = 0; t < (unsigned)(ROWS * DOUT * DIN); ++t) {\n"
        "#pragma HLS PIPELINE II=1\n"
        "        const unsigned i = t %% DIN, o = (t / DIN) %% DOUT, r = t / (DIN * DOUT);\n"
        "        const act_t x = in[(long)r * DIN + i];\n"
        "        const acc_t acc_n = (i == 0 ? (acc_t)0 : acc) + x * W[(long)o * DIN + i];\n"
        "        const long long xw = (long long)x * PROJ_WSUM[i];\n"
        "#pragma HLS BIND_OP variable=xw op=mul impl=fabric\n"
        "        const acc_t chk_n = (o == 0) ? (acc_t)((i == 0 ? (acc_t)0 : chk) + xw) : chk;\n"
        "        acc = acc_n;\n"
        "        chk = chk_n;\n"
        "        if (i == DIN - 1) {\n"
        "            acc_t a = acc_n;\n"
        "            if ((int)(r * DOUT + o) == inj_idx) a = flip32((long)a, inj_bit);   // B03 site 2\n"
        "            const long long ab = (long long)a + b[o];\n"
        "            rerr |= (ab > PROJ_ACC_BOUND) | (ab < -PROJ_ACC_BOUND);\n"
        "            out[(long)r * DOUT + o] = requant(a + b[o], Mq);\n"
        "            const acc_t rs = (o == 0 ? (acc_t)0 : rowsum) + a;\n"
        "            rowsum = rs;\n"
        "            if (o == DOUT - 1) serr |= (rs != chk_n);\n"
        "        }\n"
        "    }\n"
        "    range_err = rerr;\n"
        "    sum_err = serr;\n"
        "}\n") % (bound, din, ", ".join(map(str, wsum)))
    s = s[:start] + chk + s[end:]
    s = sub(s, "                             int& input_sig_after, int& range_err, int& tail_err,\n"
               "                             int inj_site, int inj_word, int inj_bit) {",
            "                             int& input_sig_after, int& range_err, int& tail_err, int& sum_err,\n"
            "                             int inj_site, int inj_word, int inj_bit) {")
    s = sub(s, "    linear_fixed_rangechk<SEQ, CH, D>(input, W_proj, b_proj, M_proj_q40[0], x_in, range_err,\n"
               "                                      inj_site == 2 ? inj_word : -1, inj_bit);",
            "    linear_fixed_chk<SEQ, CH, D>(input, W_proj, b_proj, M_proj_q40[0], x_in, range_err, sum_err,\n"
            "                                 inj_site == 2 ? inj_word : -1, inj_bit);")
    s = sub(s, "                     int& pred_class, int& integrity_status,\n"
               "                     int inj_site, int inj_word, int inj_bit) {",
            "                     int& pred_class, int& integrity_status\n"
            "#ifdef B04_INJECT\n"
            "                     , int inj_site, int inj_word, int inj_bit\n"
            "#endif\n"
            "                     ) {")
    s = sub(s, "#pragma HLS INTERFACE s_axilite port=inj_site bundle=ctrl\n"
               "#pragma HLS INTERFACE s_axilite port=inj_word bundle=ctrl\n"
               "#pragma HLS INTERFACE s_axilite port=inj_bit bundle=ctrl\n"
               "#pragma HLS INTERFACE s_axilite port=return bundle=ctrl\n",
            "#ifdef B04_INJECT\n"
            "#pragma HLS INTERFACE s_axilite port=inj_site bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=inj_word bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=inj_bit bundle=ctrl\n"
            "#endif\n"
            "#pragma HLS INTERFACE s_axilite port=return bundle=ctrl\n"
            "#ifndef B04_INJECT\n"
            "    const int inj_site = 0, inj_word = 0, inj_bit = 0;   // no injection hardware\n"
            "#endif\n")
    s = sub(s, "    int sig_after = 0, range_err = 0, tail_err = 0;\n"
               "    transformer_core(input, logits, sig_after, range_err, tail_err, inj_site, inj_word, inj_bit);\n"
               "    integrity_status = (sig_after != sig_before ? 1 : 0) | (tail_err << 1) | (range_err << 2);\n",
            "    int sig_after = 0, range_err = 0, tail_err = 0, sum_err = 0;\n"
            "    transformer_core(input, logits, sig_after, range_err, tail_err, sum_err, inj_site, inj_word, inj_bit);\n"
            "    integrity_status = (sig_after != sig_before ? 1 : 0) | (tail_err << 1) | (range_err << 2) | (sum_err << 3);\n")
    assert "linear_fixed_rangechk" not in s
    DST.write_text(banner + s)
    print("wrote", DST, "bound", bound, "WSUM", wsum)


def make_harnesses():
    proto_b03 = ("void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class, int& integrity_status,\n"
                 "                     int inj_site, int inj_word, int inj_bit);")
    proto_b04 = ("void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class, int& integrity_status\n"
                 "#ifdef B04_INJECT\n"
                 "                     , int inj_site, int inj_word, int inj_bit\n"
                 "#endif\n"
                 "                     );")
    bh = (B03 / "batch_logits_b03.cpp").read_text()
    bh = sub(bh, proto_b03, proto_b04)
    bh = sub(bh, "        transformer_top(in, out, pred_class, integrity_status, site, word, bit);",
             "#ifdef B04_INJECT\n"
             "        transformer_top(in, out, pred_class, integrity_status, site, word, bit);\n"
             "#else\n"
             "        transformer_top(in, out, pred_class, integrity_status);\n"
             "#endif")
    (HERE / "batch_logits_b04.cpp").write_text(
        "// B04 batch C-model harness (generated from batch_logits_b03.cpp by make_b04_top.py);\n"
        "// with -DB04_INJECT the optional argv[3] injection manifest is applied.\n" + bh)
    tb = (B03 / "testbench_b03.cpp").read_text()
    tb = sub(tb, proto_b03, proto_b04)
    tb = sub(tb, "        transformer_top(in, out, pred_class, integrity_status, 0, 0, 0);   // injection off",
             "#ifdef B04_INJECT\n"
             "        transformer_top(in, out, pred_class, integrity_status, 0, 0, 0);   // injection off\n"
             "#else\n"
             "        transformer_top(in, out, pred_class, integrity_status);\n"
             "#endif")
    (HERE / "testbench_b04.cpp").write_text(
        "// B04 HLS testbench (generated from testbench_b03.cpp by make_b04_top.py): canonical\n"
        "// goldens exact and integrity_status 0 (injection off in the b04i build).\n" + tb)
    print("wrote harnesses")


if __name__ == "__main__":
    make_top()
    make_harnesses()
