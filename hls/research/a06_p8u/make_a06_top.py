"""Generate the A06 research top (path A combined finalist) from the canonical
raw-input argmax top, which is only read:
  * attention probabilities as UNSIGNED 8-bit codes, qmax 255 (A02 variant p8u;
    all activation scales equal the canonical export, checked in A02)
  * exact 8-bit-quotient softmax divider (softmax_div_q8.h, exhaustively checked)
  * context requant multiplier for s_attn = 1/255, computed exactly as the export
    does: m = (1/255 * s_v) / s_ctx (Python float), Q40 = round_half_even(Decimal(repr(m)) * 2^40)
This is a DIFFERENT numerical model: its reference is the research p8u model
(tools/research/precision_ablation.py make_model(..., 10, 10, 8, True)), not the
canonical goldens.
"""
from __future__ import annotations

import json
from decimal import ROUND_HALF_EVEN, Decimal
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
VITIS = REPO / "hls/f1_int10_seq256/vitis"
HERE = Path(__file__).resolve().parent
SRC = VITIS / "transformer_top_seq256_raw1024_dsp_margin_argmax.cpp"
DST = HERE / "transformer_top_seq256_raw1024_p8u_argmax.cpp"
SCALES = REPO / "artifacts/quantized/f_seq256_int10/integer_config.json"


def m_ctx_q40():
    s = json.loads(SCALES.read_text())["scales"]
    m = ((1.0 / 255) * s["l0.v"]) / s["l0.ctx"]
    return int((Decimal(repr(m)) * Decimal(1 << 40)).to_integral_value(rounding=ROUND_HALF_EVEN)), m


def sub(src, old, new):
    assert src.count(old) == 1, old[:90]
    return src.replace(old, new)


def main():
    q40, m = m_ctx_q40()
    s = SRC.read_text()
    banner = ("// ---------------------------------------------------------------------------\n"
              "// A06 RESEARCH VARIANT (2026-11-13), generated by hls/research/a06_p8u/make_a06_top.py\n"
              "// from the canonical raw-input argmax top (NOT modified): unsigned 8-bit attention\n"
              "// probabilities (qmax 255), exact 8-bit-quotient softmax divider, context requant\n"
              "// multiplier for s_attn = 1/255. Different numerics: reference = research p8u model.\n"
              "// ---------------------------------------------------------------------------\n"
              "#include \"softmax_div_q8.h\"\n"
              "static const long long M_l0_ctx_p8u_q40 = %dLL;   // m = %r\n" % (q40, m))
    s = sub(s, "static const long ATTN_QMAX = 511;", "static const long ATTN_QMAX = 255;   // A06: unsigned 8-bit probabilities")
    s = sub(s, """        acc_t numerator0 = (acc_t)num[j] * ATTN_QMAX + denom / 2;
        acc_t numerator1 = (acc_t)num[j + 1] * ATTN_QMAX + denom / 2;
        qattn[j]     = numerator0 / denom;
        qattn[j + 1] = numerator1 / denom;""",
            """        acc_t numerator0 = (acc_t)num[j] * ATTN_QMAX + denom / 2;
        acc_t numerator1 = (acc_t)num[j + 1] * ATTN_QMAX + denom / 2;
        qattn[j]     = div_q8((q8_numer_t)numerator0, (q8_denom_t)denom);
        qattn[j + 1] = div_q8((q8_numer_t)numerator1, (q8_denom_t)denom);""")
    s = sub(s, "    act_t qattn[SEQ];\n", "    q8_t qattn[SEQ];\n")
    s = sub(s, "        act_t qv0 = qattn[j], qv1 = qattn[j + 1];", "        q8_t qv0 = qattn[j], qv1 = qattn[j + 1];")
    s = sub(s, "        ctxh[d] = requant(cacc0[d] + cacc1[d], M_l0_ctx_q40[0]);",
            "        ctxh[d] = requant(cacc0[d] + cacc1[d], M_l0_ctx_p8u_q40);")
    DST.write_text(banner + s)
    print("wrote", DST, "M_ctx_q40", q40, "m", m)


if __name__ == "__main__":
    main()
