"""Generate the Q02 research top: canonical raw-input argmax core + input-quality and
decision-status metadata (selected by the corrected Q01 v2 pilot,
artifacts/research/Q01v2_20261114). Canonical sources are only read.

New AXI-Lite output registers (research ABI; the class and logits are unchanged):
  quality_detail  bits 0-7  clip flag per channel  (any sample at the 24-bit code limits)
                  bits 8-15 run flag per channel   (longest run of equal consecutive codes > RUN_MAX[c])
                  bits 16-23 low-bit flag per channel (samples with nonzero low 16 bits < LOW_MIN[c])
  quality_status  bit0 any clip, bit1 any run, bit2 any low-bit, bit3 low margin (top1 - top2 < MARGIN_MIN)
  logit_margin    top1 - top2 integer logit
Thresholds = the frozen Q01 rule on CLEAN VALIDATION (summary thresholds_from_clean_validation),
converted to exact integer counts here (asserted equivalent). The counters run in a
separate II=1 pass over the raw buffer inside a copy of raw_ingress (onchip_preprocess_q02.h).

    python hls/research/q02_quality/make_q02_top.py
"""
from __future__ import annotations

import json
import math
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
VITIS = REPO / "hls/f1_int10_seq256/vitis"
HERE = Path(__file__).resolve().parent
SUMMARY = REPO / "artifacts/research/Q01v2_20261114/summary.json"


def thresholds():
    t = json.loads(SUMMARY.read_text())["thresholds_from_clean_validation"]
    assert all(c <= 1e-6 for c in t["clipped"])            # clean validation never clipped: any clipped sample flags
    run_max = [int(v) for v in t["longest"]]
    # flag iff count/1024 < thr  <=>  count < ceil(thr*1024)  (thr = clean minimum - 1e-9)
    low_min = [int(math.ceil(v * 1024)) for v in t["lowbits"]]
    for v, k in zip(t["lowbits"], low_min):
        assert (k - 1) / 1024 < v <= k / 1024
    margin = int(t["margin_min"])
    assert margin == t["margin_min"]
    return run_max, low_min, margin


def sub(src, old, new):
    assert src.count(old) == 1, old[:90]
    return src.replace(old, new)


def make():
    run_max, low_min, margin = thresholds()
    h = (VITIS / "onchip_preprocess.h").read_text()
    h = sub(h, "#ifndef ONCHIP_PREPROCESS_H\n#define ONCHIP_PREPROCESS_H",
            "// Q02 RESEARCH COPY of onchip_preprocess.h (generated by hls/research/q02_quality/make_q02_top.py):\n"
            "// raw_ingress_q = raw_ingress + per-channel quality counters on the clamped raw codes.\n"
            "#ifndef ONCHIP_PREPROCESS_Q02_H\n#define ONCHIP_PREPROCESS_Q02_H")
    h = sub(h, "static void raw_ingress(hls::stream<AXIS_T>& in, ACT_T* tokens) {",
            "static void raw_ingress_q(hls::stream<AXIS_T>& in, ACT_T* tokens, int& quality_detail) {")
    q = (
        "\nQ02_QC:\n"
        "    // Q02: per-channel quality counters on the clamped raw codes (one extra II=1 pass).\n"
        "    {\n"
        "        int clip_n[NCH], low_n[NCH], run[NCH], run_max[NCH];\n"
        "        long long prev[NCH];\n"
        "#pragma HLS ARRAY_PARTITION variable=clip_n complete\n"
        "#pragma HLS ARRAY_PARTITION variable=low_n complete\n"
        "#pragma HLS ARRAY_PARTITION variable=run complete\n"
        "#pragma HLS ARRAY_PARTITION variable=run_max complete\n"
        "#pragma HLS ARRAY_PARTITION variable=prev complete\n"
        "        for (int c = 0; c < NCH; ++c) {\n"
        "#pragma HLS UNROLL\n"
        "            clip_n[c] = 0; low_n[c] = 0; run[c] = 0; run_max[c] = 0; prev[c] = 0;\n"
        "        }\n"
        "        for (int i = 0; i < IN_SEQ * NCH; ++i) {\n"
        "#pragma HLS PIPELINE II=1\n"
        "#pragma HLS DEPENDENCE variable=clip_n inter false\n"
        "#pragma HLS DEPENDENCE variable=low_n inter false\n"
        "#pragma HLS DEPENDENCE variable=run inter false\n"
        "#pragma HLS DEPENDENCE variable=run_max inter false\n"
        "#pragma HLS DEPENDENCE variable=prev inter false\n"
        "            const int c = i %% NCH;\n"
        "            const long long v = raw[i];\n"
        "            clip_n[c] += (v == PP_CODE_MAX || v == PP_CODE_MIN) ? 1 : 0;\n"
        "            low_n[c] += ((v & 0xFFFF) != 0) ? 1 : 0;\n"
        "            const int r = (i >= NCH && v == prev[c]) ? run[c] + 1 : 0;\n"
        "            run[c] = r;\n"
        "            if (r > run_max[c]) run_max[c] = r;\n"
        "            prev[c] = v;\n"
        "        }\n"
        "        static const int Q02_RUN_MAX[NCH] = {%s};\n"
        "        static const int Q02_LOW_MIN[NCH] = {%s};\n"
        "        int d = 0;\n"
        "        for (int c = 0; c < NCH; ++c) {\n"
        "#pragma HLS UNROLL\n"
        "            d |= (clip_n[c] > 0 ? 1 : 0) << c;\n"
        "            d |= (run_max[c] > Q02_RUN_MAX[c] ? 1 : 0) << (8 + c);\n"
        "            d |= (low_n[c] < Q02_LOW_MIN[c] ? 1 : 0) << (16 + c);\n"
        "        }\n"
        "        quality_detail = d;\n"
        "    }\n") % (", ".join(map(str, run_max)), ", ".join(map(str, low_min)))
    h = sub(h, "\nPP_VAR:\n", q + "\nPP_VAR:\n")
    (HERE / "onchip_preprocess_q02.h").write_text(h)

    s = (VITIS / "transformer_top_seq256_raw1024_dsp_margin_argmax.cpp").read_text()
    banner = ("// Q02 RESEARCH VARIANT (2026-11-14), generated by hls/research/q02_quality/make_q02_top.py from\n"
              "// transformer_top_seq256_raw1024_dsp_margin_argmax.cpp (NOT modified): adds quality_detail,\n"
              "// quality_status and logit_margin metadata registers; logits and class unchanged.\n")
    s = sub(s, '#include "onchip_preprocess.h"', '#include "onchip_preprocess_q02.h"')
    s = sub(s, "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out,\n                     int& pred_class) {",
            "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out,\n"
            "                     int& pred_class, int& quality_status, int& quality_detail, int& logit_margin) {")
    s = sub(s, "#pragma HLS INTERFACE s_axilite port=pred_class bundle=ctrl\n",
            "#pragma HLS INTERFACE s_axilite port=pred_class bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=quality_status bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=quality_detail bundle=ctrl\n"
            "#pragma HLS INTERFACE s_axilite port=logit_margin bundle=ctrl\n")
    s = sub(s, "    raw_ingress<axis_t, act_t, INPUT_SEQ, SEQ, CH>(in, input);\n",
            "    int qd = 0;\n    raw_ingress_q<axis_t, act_t, INPUT_SEQ, SEQ, CH>(in, input, qd);\n")
    s = sub(s, "    pred_class = argmax_first_max<act_t, NUM_CLASSES>(logits);\n",
            "    pred_class = argmax_first_max<act_t, NUM_CLASSES>(logits);\n"
            "    // Q02 decision status: top-1 minus top-2 integer logit\n"
            "    int m1 = -100000, m2 = -100000;\n"
            "    for (int c = 0; c < NUM_CLASSES; ++c) {\n"
            "        const int v = (int)logits[c];\n"
            "        if (v > m1) { m2 = m1; m1 = v; } else if (v > m2) { m2 = v; }\n"
            "    }\n"
            "    const int margin = m1 - m2;\n"
            "    logit_margin = margin;\n"
            "    quality_detail = qd;\n"
            "    quality_status = ((qd & 0xFF) ? 1 : 0) | ((qd & 0xFF00) ? 2 : 0) | ((qd & 0xFF0000) ? 4 : 0)\n"
            "                   | (margin < %d ? 8 : 0);\n" % margin)
    (HERE / "transformer_top_seq256_raw1024_q02_argmax.cpp").write_text(banner + s)

    b = (REPO / "hls/f1_int10_seq256/gpp_csim/batch_logits.cpp").read_text()
    b = sub(b, "#ifdef WITH_PRED_CLASS\nvoid transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class);",
            "#ifdef WITH_PRED_CLASS\nvoid transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class,\n"
            "                     int& quality_status, int& quality_detail, int& logit_margin);")
    b = sub(b, "        int pred_class = -1;\n        transformer_top(in, out, pred_class);",
            "        int pred_class = -1, qs = -1, qd = -1, lm = -1;\n        transformer_top(in, out, pred_class, qs, qd, lm);")
    b = sub(b, "        std::printf(\"%ld %lld %lld %lld %lld %d\\n\", first + done, lg[0], lg[1], lg[2], lg[3],\n                    pred_class);",
            "        std::printf(\"%ld %lld %lld %lld %lld %d %d %d %d\\n\", first + done, lg[0], lg[1], lg[2], lg[3],\n"
            "                    pred_class, qs, qd, lm);")
    (HERE / "batch_logits_q02.cpp").write_text(
        "// Q02 batch C-model harness (generated by make_q02_top.py from gpp_csim/batch_logits.cpp);\n"
        "// columns: idx logit0..3 pred_class quality_status quality_detail logit_margin.\n" + b)
    t = (VITIS / "testbench_ingress1024_argmax.cpp").read_text()
    t = sub(t, "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class);",
            "void transformer_top(hls::stream<axis_t>& in, hls::stream<axis_t>& out, int& pred_class,\n"
            "                     int& quality_status, int& quality_detail, int& logit_margin);")
    t = sub(t, "        int pred_class = -1;\n        transformer_top(in, out, pred_class);",
            "        int pred_class = -1, qs = -1, qd = -1, lm = -1;\n        transformer_top(in, out, pred_class, qs, qd, lm);")
    (HERE / "testbench_q02.cpp").write_text(
        "// Q02 HLS testbench (generated by make_q02_top.py): canonical goldens exact (logits + class);\n"
        "// the quality registers are checked against the Python reference by tools/research/q02_check.py.\n" + t)
    print("wrote Q02 sources; RUN_MAX", run_max, "LOW_MIN", low_min, "MARGIN_MIN", margin)


if __name__ == "__main__":
    make()
