"""
Data augmentation utilities for the training split.

This module provides augmentation helpers for time-windowed samples used in
the MAFAULDA pipeline.

Supported augmentation methods
------------------------------
1. Noise injection
   Adds Gaussian noise to the existing samples.

2. SMOTE-like oversampling
   Generates synthetic samples for minority classes by interpolating between
   nearest neighbors in the flattened feature space.

Important
---------
- Augmentation should be applied to training data only.
- Validation and test data must remain unchanged.
- The current SMOTE implementation requires the full training arrays in memory.
  This means it is not directly compatible with a fully lazy/on-the-fly dataset
  pipeline without an intermediate materialization step.
"""

import numpy as np
from sklearn.neighbors import NearestNeighbors

from src.config import NOISE_INJECTION_STD, RANDOM_SEED


def flatten_samples(X):
    """
    Flatten each sample into a 1D feature vector.

    Parameters
    ----------
    X : array-like
        Input samples with shape [num_samples, ...].

    Returns
    -------
    np.ndarray
        Flattened array with shape [num_samples, num_features].

    Notes
    -----
    This is useful for algorithms such as nearest-neighbor search, which
    expect 2D input in the form [samples, features].
    """
    X = np.asarray(X, dtype=np.float32)
    return X.reshape(X.shape[0], -1)


def restore_sample_shape(X_flat, sample_shape):
    """
    Restore flattened samples to their original per-sample shape.

    Parameters
    ----------
    X_flat : array-like
        Flattened sample array with shape [num_samples, num_features].
    sample_shape : tuple
        Original shape of one sample, for example (1024, 8).

    Returns
    -------
    np.ndarray
        Restored array with shape [num_samples, *sample_shape].
    """
    X_flat = np.asarray(X_flat, dtype=np.float32)
    return X_flat.reshape((-1, *sample_shape))


def apply_noise_injection(X, noise_std=NOISE_INJECTION_STD, random_state=RANDOM_SEED):
    """
    Apply Gaussian noise injection to the input samples.

    Parameters
    ----------
    X : array-like
        Input samples.
    noise_std : float, default=NOISE_INJECTION_STD
        Standard deviation of the Gaussian noise.
    random_state : int, default=RANDOM_SEED
        Random seed for reproducibility.

    Returns
    -------
    np.ndarray
        Noisy version of the input samples with dtype float32.

    Notes
    -----
    The output has the same shape as the input.
    """
    X = np.asarray(X, dtype=np.float32)
    if X.size == 0:
        return X

    rng = np.random.default_rng(random_state)
    noise = rng.normal(loc=0.0, scale=noise_std, size=X.shape).astype(np.float32)
    return (X + noise).astype(np.float32)


def apply_smote(X, y, random_state=RANDOM_SEED, k_neighbors=5):
    """
    Apply a simple SMOTE-like oversampling procedure to minority classes.

    Parameters
    ----------
    X : array-like
        Input samples with shape [num_samples, ...].
    y : array-like
        Integer class labels with shape [num_samples].
    random_state : int, default=RANDOM_SEED
        Random seed for reproducibility.
    k_neighbors : int, default=5
        Maximum number of nearest neighbors used for interpolation.

    Returns
    -------
    tuple
        (X_aug, y_aug)

        - X_aug : np.ndarray
            Augmented samples with the original sample shape restored
        - y_aug : np.ndarray
            Corresponding labels

    Notes
    -----
    - Samples are first flattened so nearest-neighbor search can operate on
      2D feature vectors.
    - For each minority class, synthetic samples are generated by interpolating
      between a randomly chosen sample and one of its nearest neighbors from
      the same class.
    - Classes with fewer than 2 samples are skipped because interpolation
      requires at least two points.
    """
    X = np.asarray(X, dtype=np.float32)
    y = np.asarray(y, dtype=np.int64)

    if X.size == 0 or y.size == 0:
        return X, y

    sample_shape = X.shape[1:]
    X_flat = flatten_samples(X)

    class_counts = np.bincount(y)
    target_count = class_counts.max()

    rng = np.random.default_rng(random_state)
    synthetic_samples = []
    synthetic_labels = []

    for class_id, class_count in enumerate(class_counts):
        # Skip empty classes and classes that already match the majority count.
        if class_count == 0 or class_count >= target_count:
            continue

        class_samples = X_flat[y == class_id]
        if class_samples.shape[0] < 2:
            continue

        neighbor_count = min(k_neighbors, class_samples.shape[0] - 1)
        neighbors = NearestNeighbors(n_neighbors=neighbor_count + 1)
        neighbors.fit(class_samples)

        # The first returned neighbor is the sample itself, so it is removed.
        neighbor_indices = neighbors.kneighbors(class_samples, return_distance=False)[:, 1:]

        samples_needed = target_count - class_count
        for _ in range(samples_needed):
            base_idx = int(rng.integers(0, class_samples.shape[0]))
            candidate_neighbors = neighbor_indices[base_idx]
            neighbor_idx = int(rng.choice(candidate_neighbors))

            base_sample = class_samples[base_idx]
            neighbor_sample = class_samples[neighbor_idx]

            # Interpolate between two same-class samples.
            gap = float(rng.random())
            synthetic = base_sample + gap * (neighbor_sample - base_sample)

            synthetic_samples.append(synthetic.astype(np.float32))
            synthetic_labels.append(class_id)

    if not synthetic_samples:
        return X, y

    X_aug = np.vstack([X_flat, np.vstack(synthetic_samples)])
    y_aug = np.concatenate([y, np.asarray(synthetic_labels, dtype=np.int64)])

    return restore_sample_shape(X_aug, sample_shape), y_aug


def augment_training_data(
    X,
    y,
    use_smote=False,
    use_noise_injection=False,
    noise_std=NOISE_INJECTION_STD,
    random_state=RANDOM_SEED,
):
    """
    Apply selected augmentation methods to training data.

    Parameters
    ----------
    X : array-like
        Training samples.
    y : array-like
        Training labels.
    use_smote : bool, default=False
        Whether to apply SMOTE-like oversampling.
    use_noise_injection : bool, default=False
        Whether to apply Gaussian noise injection.
    noise_std : float, default=NOISE_INJECTION_STD
        Standard deviation of Gaussian noise used for noise injection.
    random_state : int, default=RANDOM_SEED
        Random seed for reproducibility.

    Returns
    -------
    tuple
        (X_aug, y_aug, augmentation_info)

        - X_aug : np.ndarray
            Augmented training samples
        - y_aug : np.ndarray
            Corresponding labels
        - augmentation_info : dict
            Summary of what augmentation was applied

    Notes
    -----
    Augmentation order:
    1. Optional SMOTE
    2. Optional noise injection

    If noise injection is enabled, a noisy copy of the current dataset is
    created and concatenated to the original dataset, doubling the number of
    samples at that stage.
    """
    X = np.asarray(X, dtype=np.float32)
    y = np.asarray(y, dtype=np.int64)

    if X.size == 0 or y.size == 0:
        return X, y, {
            "smote_applied": False,
            "noise_injection_applied": False,
            "original_samples": int(len(y)),
            "augmented_samples": int(len(y)),
        }

    original_samples = int(len(y))

    if use_smote:
        X, y = apply_smote(X, y, random_state=random_state)

    if use_noise_injection:
        X_noisy = apply_noise_injection(X, noise_std=noise_std, random_state=random_state)
        X = np.concatenate([X, X_noisy], axis=0)
        y = np.concatenate([y, y.copy()], axis=0)

    augmentation_info = {
        "smote_applied": bool(use_smote),
        "noise_injection_applied": bool(use_noise_injection),
        "noise_std": float(noise_std),
        "original_samples": original_samples,
        "augmented_samples": int(len(y)),
    }

    return X.astype(np.float32), y.astype(np.int64), augmentation_info